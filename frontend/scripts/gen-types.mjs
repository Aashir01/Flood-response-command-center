// JSON Schema -> TypeScript. Re-runnable: `npm run gen:types`.
// Reads packages/stitch_common/schemas/*.json (exported from the Pydantic models) and
// writes src/gen/contracts.ts, one TypeScript namespace per schema file.
import { compile } from 'json-schema-to-typescript';
import { readdirSync, readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..');
const schemaDir = join(root, 'packages', 'stitch_common', 'schemas');
const lock = JSON.parse(readFileSync(join(root, 'packages', 'stitch_common', 'contracts.lock.json'), 'utf8'));

const nsName = (file) =>
  file
    .replace(/\.json$/, '')
    .split(/[._]/)
    .map((p) => p.charAt(0).toUpperCase() + p.slice(1))
    .join('');

const files = readdirSync(schemaDir).filter((f) => f.endsWith('.json')).sort();
let out = `/* eslint-disable */
// GENERATED by scripts/gen-types.mjs from packages/stitch_common/schemas. Do not edit.
// CONTRACT_VERSION: ${lock.contract_version}
export const CONTRACT_VERSION = ${JSON.stringify(lock.contract_version)} as const;
`;
for (const file of files) {
  const schema = JSON.parse(readFileSync(join(schemaDir, file), 'utf8'));
  const ts = await compile(schema, nsName(file), {
    bannerComment: '',
    additionalProperties: false,
    format: false,
    strictIndexSignatures: false,
    unreachableDefinitions: true,
    cwd: schemaDir,
  });
  out += `\nexport namespace ${nsName(file)} {\n${ts.split('\n').map((l) => (l ? '  ' + l : l)).join('\n')}\n}\n`;
}
mkdirSync(join(root, 'frontend', 'src', 'gen'), { recursive: true });
writeFileSync(join(root, 'frontend', 'src', 'gen', 'contracts.ts'), out);
console.log(`wrote src/gen/contracts.ts (${files.length} schemas, contract ${lock.contract_version})`);
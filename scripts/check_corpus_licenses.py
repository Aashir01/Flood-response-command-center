"""Library corpus license check (LIB-P6, design section 3.3) and generated docs.

    uv run python scripts/check_corpus_licenses.py [--require-owner-confirmed] [--write-docs]

Rules (each failure is reported; exit status 1 if any):
1. Every manifest entry has every field (the manifest model enforces this).
2. ``tier: committed`` needs ``redistributable: true`` and non-empty ``license_evidence``.
   ``owner_confirmed: false`` is a warning, or a failure with ``--require-owner-confirmed``.
3. Every tracked file under ``data/demo/library/corpus/`` or ``data/demo/library/pack/`` belongs
   to a committed entry (corpus: its ``path``; pack: every doc id listed in ``pack.json`` must be
   committed). Derived artifacts of non-redistributable documents are never committed.
4. ``tier: fetch`` entries have a ``source_url`` and no ``path``; committed files hash to their
   ``sha256`` (text files with LF line endings).
5. ``git ls-files data/raw`` is empty.

``--write-docs`` regenerates ``data/demo/MANIFEST.md`` (the Library section between markers) and
the ``## Library corpus (per document)`` table in ``THIRD_PARTY.md``.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import subprocess
import sys
from collections.abc import Iterable, Mapping
from dataclasses import dataclass
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
LIB = "data/demo/library"
BEGIN = "<!-- library-corpus:begin (generated by scripts/check_corpus_licenses.py) -->"
END = "<!-- library-corpus:end -->"


@dataclass(frozen=True)
class Problem:
    rule: int
    message: str
    warning: bool = False


def check(
    entries: list[dict[str, object]],
    tracked: Iterable[str],
    pack_doc_ids: Iterable[str] | None,
    file_hashes: Mapping[str, str] | None = None,
    *,
    require_owner: bool = False,
) -> list[Problem]:
    """Pure check over manifest entries (as dicts), tracked repo paths and the pack's doc ids."""
    from pydantic import ValidationError

    from stitch_library.ingest.manifest import ManifestEntry

    problems: list[Problem] = []
    valid: dict[str, ManifestEntry] = {}
    for i, raw in enumerate(entries):
        try:
            e = ManifestEntry.model_validate(raw)
        except ValidationError as exc:
            fields = sorted({".".join(str(p) for p in err["loc"]) for err in exc.errors()})
            problems.append(Problem(1, f"entry {i}: invalid or missing {', '.join(fields)}"))
            continue
        valid[e.doc_id] = e
    committed = {d: e for d, e in valid.items() if e.tier == "committed"}
    for d, e in committed.items():
        if not e.redistributable:
            problems.append(Problem(2, f"{d}: committed but redistributable is false"))
        if not e.license_evidence.strip():
            problems.append(Problem(2, f"{d}: committed without license_evidence"))
        if not e.owner_confirmed:
            problems.append(Problem(2, f"{d}: owner_confirmed is false", warning=not require_owner))
    paths = {f"{LIB}/{e.path}": d for d, e in committed.items() if e.path}
    allowed = {d for d, e in committed.items() if e.redistributable}
    for f in sorted(set(tracked)):
        if f.startswith(f"{LIB}/corpus/"):
            owner = paths.get(f)
            if owner is None or owner not in allowed:
                problems.append(
                    Problem(
                        3, f"{f}: tracked corpus file without a redistributable committed entry"
                    )
                )
        elif f.startswith("data/raw/"):
            problems.append(Problem(5, f"{f}: data/raw must never be tracked"))
    for d in sorted(set(pack_doc_ids or [])):
        if d not in allowed:
            problems.append(
                Problem(
                    3,
                    f"pack contains derived data of {d!r}, which is not a redistributable committed entry",  # noqa: E501
                )
            )
    if file_hashes is not None:
        for f, d in paths.items():
            got = file_hashes.get(f)
            want = committed[d].sha256
            if got is None:
                problems.append(Problem(4, f"{d}: committed file {f} is missing"))
            elif got != want:
                problems.append(Problem(4, f"{d}: sha256 of {f} is {got}, manifest says {want}"))
    return problems


def _git_ls(root: Path, *paths: str) -> list[str]:
    res = subprocess.run(
        ["git", "ls-files", *paths], cwd=root, capture_output=True, text=True, check=False
    )
    return [line.strip() for line in res.stdout.splitlines() if line.strip()]


def file_sha(path: Path) -> str:
    data = path.read_bytes()
    if path.suffix in (".txt", ".md"):
        data = data.replace(b"\r\n", b"\n")
    return hashlib.sha256(data).hexdigest()


def _manifest_md(entries: list[dict[str, object]]) -> str:
    lines = [
        BEGIN,
        "## Library corpus (library-mcp)",
        "",
        "Generated from `data/demo/library/manifest.yaml`. Only `tier: committed` documents are in the",  # noqa: E501
        "repo; `tier: fetch` documents are downloaded by `scripts/fetch_corpus.py` into the git-ignored",  # noqa: E501
        "`data/raw/library/`. Committed English documents are text renditions of US federal web pages",  # noqa: E501
        "(public domain under 17 U.S.C. 105); committed Urdu documents are unofficial translations by",  # noqa: E501
        "the Stitch team (CC BY 4.0), pending a native-speaker review. `owner_confirmed: false` means",  # noqa: E501
        "the license evidence was checked by the implementing agent, not yet by the owner.",
        "",
        "| doc_id | Title | Publisher | Lang | License | Redistributable | Tier | Owner confirmed | Source | License evidence |",  # noqa: E501
        "|---|---|---|---|---|---|---|---|---|---|",
    ]
    for e in entries:
        ev = str(e.get("license_evidence", "")).replace("|", "/").replace("\n", " ")
        lines.append(
            f"| `{e['doc_id']}` | {e['title']} | {e['publisher']} | {e['lang']} | {e['license']} | "
            f"{'yes' if e['redistributable'] else 'no'} | {e['tier']} | "
            f"{'yes' if e['owner_confirmed'] else 'no'} | {e['source_url']} | {ev} |"
        )
    lines += ["", END]
    return "\n".join(lines)


def _third_party_rows(entries: list[dict[str, object]]) -> str:
    rows = [
        "| Document | Publisher | License / terms | Redistributable | Committed |",
        "|---|---|---|---|---|",
    ]
    for e in entries:
        rows.append(
            f"| {e['title']} (`{e['doc_id']}`) | {e['publisher']} | {e['license']} | "
            f"{'yes' if e['redistributable'] else 'no'} | "
            f"{'yes' if e['tier'] == 'committed' else 'no (fetched by script)'} |"
        )
    return "\n".join(rows)


def write_docs(root: Path, entries: list[dict[str, object]]) -> None:
    md = root / "data" / "demo" / "MANIFEST.md"
    text = md.read_text(encoding="utf-8") if md.exists() else "# Demo data manifest\n"
    block = _manifest_md(entries)
    if BEGIN in text and END in text:
        head, rest = text.split(BEGIN, 1)
        _, tail = rest.split(END, 1)
        text = head + block + tail
    else:
        text = text.rstrip() + "\n\n" + block + "\n"
    md.write_text(text, encoding="utf-8", newline="\n")
    tp = root / "THIRD_PARTY.md"
    t = tp.read_text(encoding="utf-8")
    heading = "## Library corpus (per document)"
    start = t.index(heading)
    nxt = t.find("\n## ", start + len(heading))
    section = t[start : nxt if nxt != -1 else len(t)]
    table_start = section.index("| Document |")
    new_section = section[:table_start] + _third_party_rows(entries) + "\n"
    t = t[:start] + new_section + (t[nxt:] if nxt != -1 else "")
    tp.write_text(t, encoding="utf-8", newline="\n")


def main(argv: list[str] | None = None) -> int:
    import yaml

    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--require-owner-confirmed", action="store_true")
    parser.add_argument("--write-docs", action="store_true")
    parser.add_argument("--root", type=Path, default=REPO_ROOT)
    args = parser.parse_args(argv)
    root: Path = args.root
    raw = yaml.safe_load((root / LIB / "manifest.yaml").read_text(encoding="utf-8")) or []
    tracked = _git_ls(root, f"{LIB}/corpus", f"{LIB}/pack", "data/raw")
    pack_json = root / LIB / "pack" / "pack.json"
    pack_ids = (
        json.loads(pack_json.read_text(encoding="utf-8")).get("doc_ids", [])
        if pack_json.exists()
        else []
    )
    hashes = {
        f"{LIB}/{e['path']}": file_sha(root / LIB / str(e["path"]))
        for e in raw
        if isinstance(e, dict)
        and e.get("tier") == "committed"
        and e.get("path")
        and (root / LIB / str(e["path"])).exists()
    }
    problems = check(raw, tracked, pack_ids, hashes, require_owner=args.require_owner_confirmed)
    for p in problems:
        print(f"{'warning' if p.warning else 'error'} (rule {p.rule}): {p.message}")
    errors = [p for p in problems if not p.warning]
    if args.write_docs and not errors:
        write_docs(root, raw)
        print("wrote data/demo/MANIFEST.md and THIRD_PARTY.md library corpus table")
    n_c = sum(1 for e in raw if e.get("tier") == "committed")
    print(f"{len(raw)} documents ({n_c} committed); {len(errors)} error(s)")
    return 1 if errors else 0


if __name__ == "__main__":
    sys.exit(main())
